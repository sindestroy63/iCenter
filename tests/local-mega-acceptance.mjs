import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { chromium } from "@playwright/test";

const baseURL = process.env.TEST_APP_URL ?? "http://localhost:3111";
const credentials = JSON.parse(await readFile(".tmp/test-admin-credentials/credentials.json", "utf8"));
const admin = credentials.accounts.find((entry) => entry.email === "admin@icenter.ru");
assert.ok(admin);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
const consoleErrors = [];
page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });
page.on("pageerror", (error) => consoleErrors.push(error.message));
page.on("response", (response) => { if (response.status() >= 400) consoleErrors.push(`${response.status()} ${response.url()}`); });
await page.context().tracing.start({ screenshots: true, snapshots: true, sources: true });
try {
  await page.goto(`${baseURL}/admin/login`);
  await page.locator('input[type="email"]').fill(admin.email);
  await page.locator('input[type="password"]').fill(process.env.TEST_ADMIN_PASSWORD ?? admin.password);
  await page.locator('button[type="submit"]').click();
  await page.waitForTimeout(500);
  async function completePasswordChangeIfNeeded() {
    if (!page.url().includes('/admin/change-password')) return;
    const nextPassword = `Qa-${Date.now()}-MegaMenu!`;
    await page.locator('input[autocomplete="current-password"]').fill(process.env.TEST_ADMIN_PASSWORD ?? admin.password);
    await page.locator('input[autocomplete="new-password"]').first().fill(nextPassword);
    await page.locator('input[autocomplete="new-password"]').nth(1).fill(nextPassword);
    await page.locator('button[type="submit"]').click();
    await page.waitForTimeout(500);
    if (!page.url().includes('/admin') || page.url().includes('/change-password')) throw new Error(`password change failed: ${page.url()}`);
  }
  console.log(JSON.stringify({ afterLoginUrl: page.url(), title: await page.title(), body: (await page.locator("body").innerText()).slice(0, 1000), consoleErrors }));
  await page.goto(`${baseURL}/admin/catalog-menu`);
  await completePasswordChangeIfNeeded();
  if (page.url().includes('/admin/login')) throw new Error(`admin login failed: ${page.url()}`);
  console.log(JSON.stringify({ menuUrl: page.url(), menuTitle: await page.title(), menuBody: (await page.locator("body").innerText()).slice(0, 1500), consoleErrors }));
  const oldTest = page.locator('.catalog-menu-tree-select').filter({ hasText: "Test Category" });
  if (await oldTest.count()) {
    await oldTest.first().click();
    page.once("dialog", (dialog) => dialog.accept());
    await page.locator('.catalog-menu-editor-head button.danger').click();
    await page.locator('header.workspace-head button').first().click();
    await page.waitForTimeout(300);
    await page.reload();
  }
  await page.locator(".catalog-menu-tree-toolbar button").click();
  const title = page.locator('.catalog-menu-editor input:not([type="checkbox"])').first();
  await title.fill("Test Category");
  const bannerFile = page.locator('.catalog-menu-upload input[type="file"]');
  await bannerFile.setInputFiles("public/assets/iphone.png");
  await page.waitForTimeout(400);
  await page.locator('.catalog-menu-editor > button.admin-secondary').click();
  await page.locator('.catalog-menu-editor input:not([type="checkbox"])').first().fill("Test iPhone");
  const action = page.locator('.catalog-menu-editor select').filter({ has: page.locator('option[value="url"]') }).first();
  await action.selectOption("url");
  await page.locator('.catalog-menu-editor input:not([type="checkbox"])').nth(2).fill("/catalog");
  await page.locator('.catalog-menu-tree-select').filter({ hasText: "Test Category" }).click();
  await page.locator('.catalog-menu-editor > button.admin-secondary').click();
  await page.locator('.catalog-menu-editor input:not([type="checkbox"])').first().fill("Test iPad");
  await page.locator('.catalog-menu-editor select').filter({ has: page.locator('option[value="filters"]') }).first().selectOption("filters");
  const rules = page.locator('.catalog-menu-rule');
  await rules.first().locator('select').first().selectOption("brand");
  await rules.first().locator('select').last().selectOption("test-apple");
  await page.locator('.catalog-menu-rules .admin-secondary').click();
  await rules.nth(1).locator('select').first().selectOption("type");
  await rules.nth(1).locator('select').last().selectOption("test-ipad");
  const save = page.locator('header.workspace-head button').first();
  await save.click();
  await page.waitForTimeout(300);
  await page.reload();
  const treeText = await page.locator(".catalog-menu-tree").innerText();
  assert.ok(treeText.includes("Test Category"));
  assert.ok(treeText.includes("Test iPhone") && treeText.includes("Test iPad"));
  await page.locator('.catalog-menu-tree-select').filter({ hasText: "Test Category" }).click();
  assert.ok(await page.locator('.catalog-menu-preview img').count() > 0);
  const menuResponse = await page.goto(`${baseURL}/api/catalog/menu?city=samara`);
  const menu = await menuResponse.json();
  assert.ok(menu.data.some((item) => item.title === "Test Category"));
  const root = menu.data.find((item) => item.title === "Test Category");
  assert.equal(root.children.length, 2);
  const filteredId = root.children.find((item) => item.title === "Test iPad").id;
  const filteredResponse = await page.request.get(`${baseURL}/api/catalog/products?city=samara&menuItem=${encodeURIComponent(filteredId)}&limit=100&offset=0`);
  assert.equal(filteredResponse.status(), 200);
  const filtered = await filteredResponse.json();
  assert.ok(filtered.data.some((item) => item.name === "Test iPad Product"));
  assert.ok(filtered.data.every((item) => item.type?.slug === "ipad"));
  await page.goto(`${baseURL}/admin/catalog-menu`);
  await page.locator('.catalog-menu-tree-select').filter({ hasText: "Test Category" }).click();
  page.once("dialog", (dialog) => dialog.accept());
  await page.locator('.catalog-menu-editor-head button.danger').click();
  await save.click();
  await page.reload();
  assert.equal(await page.locator('.catalog-menu-tree-select').filter({ hasText: "Test Category" }).count(), 0);
  console.log("mega-menu admin login, create, save, reload and public read passed");
} finally {
  await page.screenshot({ path: ".tmp/local-mega-acceptance.png", fullPage: true }).catch(() => {});
  await page.context().tracing.stop({ path: ".tmp/local-mega-acceptance.zip" }).catch(() => {});
  await browser.close();
}
